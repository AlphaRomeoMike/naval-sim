import { defineConfig } from 'vitest/config';
import type { Plugin } from 'vite';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

/**
 * Offline play: after the build, write dist/sw.js, a service worker that pre-caches every built file
 * (code, unit data, map) and serves them cache-first. Hand-written instead of a PWA plugin: it is 25 lines
 * and adds no dependency. The cache name is a hash of the file list and contents, so a new build replaces it.
 * Files are fetched past the browser's HTTP cache ('reload'), or a host with long cache lifetimes could hand
 * a new service worker the previous build's page.
 */
function serviceWorker(): Plugin {
  return {
    name: 'flagplot-service-worker',
    apply: 'build',
    closeBundle() {
      const dist = join(__dirname, 'dist');
      const walk = (d: string): string[] => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
      let files: string[];
      try { files = walk(dist).filter((f) => !f.endsWith('sw.js')); } catch { return; } // not a client build (e.g. --ssr to another folder)
      if (!files.some((f) => f.endsWith('index.html'))) return;
      const hash = createHash('sha256');
      for (const f of files.sort()) hash.update(relative(dist, f)).update(readFileSync(f));
      // The page is cached once, as './': some hosts answer index.html with a redirect, and a redirected response cannot serve a navigation.
      const list = ['./', ...files.map((f) => relative(dist, f).split('\\').join('/')).filter((f) => f !== 'index.html')];
      writeFileSync(join(dist, 'sw.js'), `// Generated by vite.config.ts. Pre-caches the whole game for offline play.
const CACHE = 'flagplot-${hash.digest('hex').slice(0, 16)}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('flagplot-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return; // the entitlement worker is never cached
  // cache first; every page navigation (any query string, or index.html by name) gets the one cached page
  e.respondWith((e.request.mode === 'navigate' ? caches.match('./') : caches.match(e.request)).then((hit) => hit || fetch(e.request)));
});
`);
    },
  };
}

export default defineConfig({
  base: './', // works from any static host path
  build: { target: 'es2022', assetsInlineLimit: 0 },
  worker: { format: 'es' },
  plugins: [serviceWorker()],
  test: { include: ['test/**/*.test.ts'], testTimeout: 120000 },
});
